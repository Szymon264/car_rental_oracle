   WYPOŻYCZALNIA SAMOCHODÓW – schemat Oracle (3NF)
   Na bazie: github.com/tinyHiker/SQL_Rental_Database_Design
   Docelowo: Oracle 19c / 21c / 23ai (np. Oracle APEX / Autonomous DB)

   Sekcje:
     0. Usunięcie istniejących obiektów (można uruchamiać wielokrotnie)
     1. Tabele słownikowe   (MAKES, MAINTENANCE_TYPES, PROMOTIONS)
     2. Tabele główne       (USERS, BRANCHES, VEHICLE_TYPES, EMPLOYEES,
                             CUSTOMERS, VEHICLES)
     3. Tabele transakcyjne (BOOKINGS, PAYMENT_DETAILS, TRANSACTIONS,
                             DAMAGES, MAINTENANCE)
     4. Indeksy na kluczach obcych
     5. Dane przykładowe
   ===================================================================== */


/* =====================================================================
   0. DROP – bezpieczne usuwanie (ignoruje "table does not exist")
   ===================================================================== */
BEGIN
  FOR t IN (SELECT table_name FROM user_tables
             WHERE table_name IN ('TRANSACTIONS','DAMAGES','MAINTENANCE',
                                  'PAYMENT_DETAILS','BOOKINGS','VEHICLES',
                                  'CUSTOMERS','EMPLOYEES','VEHICLE_TYPES',
                                  'BRANCHES','USERS','PROMOTIONS',
                                  'MAINTENANCE_TYPES','MAKES'))
  LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/


/* =====================================================================
   1. TABELE SŁOWNIKOWE
   ===================================================================== */

-- Marki pojazdów (wydzielone z VehicleTypes: Model -> Make było zależnością przechodnią)
CREATE TABLE makes (
  make_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
  make_name    VARCHAR2(50 CHAR) NOT NULL,
  CONSTRAINT uq_makes_name UNIQUE (make_name)
);

-- Rodzaje czynności serwisowych
CREATE TABLE maintenance_types (
  maintenance_type_id  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
  type_name            VARCHAR2(60 CHAR) NOT NULL,
  interval_km          NUMBER(7),            -- co ile km wykonywać (NULL = doraźnie)
  CONSTRAINT uq_mtype_name UNIQUE (type_name),
  CONSTRAINT ck_mtype_interval CHECK (interval_km IS NULL OR interval_km > 0)
);

-- Kody promocyjne / rabaty sezonowe
CREATE TABLE promotions (
  promotion_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
  promo_code        VARCHAR2(20 CHAR) NOT NULL,
  description       VARCHAR2(200 CHAR),
  discount_percent  NUMBER(5,2) NOT NULL,
  valid_from        DATE NOT NULL,
  valid_to          DATE NOT NULL,
  CONSTRAINT uq_promo_code UNIQUE (promo_code),
  CONSTRAINT ck_promo_discount CHECK (discount_percent > 0 AND discount_percent <= 100),
  CONSTRAINT ck_promo_dates CHECK (valid_to >= valid_from)
);


/* =====================================================================
   2. TABELE GŁÓWNE
   ===================================================================== */

-- Nadklasa: użytkownik systemu (pracownik lub klient)
CREATE TABLE users (
  user_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
  first_name      VARCHAR2(40 CHAR)  NOT NULL,
  last_name       VARCHAR2(60 CHAR)  NOT NULL,
  middle_name     VARCHAR2(40 CHAR),
  street          VARCHAR2(100 CHAR) NOT NULL,
  city            VARCHAR2(60 CHAR)  NOT NULL,
  region          VARCHAR2(40 CHAR)  NOT NULL,   -- województwo
  zip_code        VARCHAR2(10 CHAR)  NOT NULL,
  country         VARCHAR2(40 CHAR)  DEFAULT 'Polska' NOT NULL,
  date_of_birth   DATE               NOT NULL,
  email           VARCHAR2(254 CHAR) NOT NULL,
  phone_number    VARCHAR2(15 CHAR)  NOT NULL,
  password_hash   VARCHAR2(255 CHAR) NOT NULL,   -- przechowujemy HASH, nie hasło
  created_at      DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT uq_users_email UNIQUE (email),
  CONSTRAINT ck_users_email CHECK (REGEXP_LIKE(email, '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$')),
  CONSTRAINT ck_users_phone CHECK (REGEXP_LIKE(phone_number, '^\+?[0-9]{9,14}$'))
);

-- Oddziały wypożyczalni
CREATE TABLE branches (
  branch_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
  branch_name   VARCHAR2(60 CHAR)  NOT NULL,
  street        VARCHAR2(100 CHAR) NOT NULL,
  city          VARCHAR2(60 CHAR)  NOT NULL,
  region        VARCHAR2(40 CHAR)  NOT NULL,
  zip_code      VARCHAR2(10 CHAR)  NOT NULL,
  country       VARCHAR2(40 CHAR)  DEFAULT 'Polska' NOT NULL,
  phone_number  VARCHAR2(15 CHAR)  NOT NULL,
  CONSTRAINT uq_branches_name  UNIQUE (branch_name),
  CONSTRAINT uq_branches_phone UNIQUE (phone_number)
);

-- Typ / model pojazdu (osobówka CAR lub dostawczy TRUCK – dawne podklasy Car/Truck)
CREATE TABLE vehicle_types (
  vehicle_type_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
  make_id            NUMBER            NOT NULL,
  model_name         VARCHAR2(50 CHAR) NOT NULL,
  production_year    NUMBER(4)         NOT NULL,
  category           VARCHAR2(10 CHAR) DEFAULT 'CAR' NOT NULL,
  daily_rate         NUMBER(8,2)       NOT NULL,
  seating_capacity   NUMBER(2)         NOT NULL,
  max_load_kg        NUMBER(5),        -- tylko TRUCK
  cargo_capacity_m3  NUMBER(5,1),      -- tylko TRUCK
  fuel_type          VARCHAR2(10 CHAR) DEFAULT 'PETROL' NOT NULL,
  transmission       VARCHAR2(10 CHAR) DEFAULT 'MANUAL' NOT NULL,
  CONSTRAINT fk_vtype_make FOREIGN KEY (make_id) REFERENCES makes(make_id),
  CONSTRAINT uq_vtype UNIQUE (make_id, model_name, production_year),
  CONSTRAINT ck_vtype_category CHECK (category IN ('CAR','TRUCK')),
  CONSTRAINT ck_vtype_year CHECK (production_year BETWEEN 1990 AND 2100),
  CONSTRAINT ck_vtype_rate CHECK (daily_rate > 0),
  CONSTRAINT ck_vtype_seats CHECK (seating_capacity BETWEEN 1 AND 50),
  CONSTRAINT ck_vtype_fuel CHECK (fuel_type IN ('PETROL','DIESEL','ELECTRIC','HYBRID','LPG')),
  CONSTRAINT ck_vtype_trans CHECK (transmission IN ('MANUAL','AUTOMATIC')),
  CONSTRAINT ck_vtype_truck_attr CHECK (
        category = 'TRUCK'
     OR (max_load_kg IS NULL AND cargo_capacity_m3 IS NULL))
);

-- Podklasa USERS: pracownik
CREATE TABLE employees (
  user_id         NUMBER       PRIMARY KEY,
  branch_id       NUMBER       NOT NULL,
  monthly_salary  NUMBER(10,2) NOT NULL,
  pesel           CHAR(11)     NOT NULL,
  employee_role   VARCHAR2(10 CHAR) DEFAULT 'CLERK' NOT NULL,  -- przyda się do autoryzacji w APEX
  hire_date       DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT fk_emp_user   FOREIGN KEY (user_id)   REFERENCES users(user_id) ON DELETE CASCADE,
  CONSTRAINT fk_emp_branch FOREIGN KEY (branch_id) REFERENCES branches(branch_id),
  CONSTRAINT uq_emp_pesel  UNIQUE (pesel),
  CONSTRAINT ck_emp_pesel  CHECK (REGEXP_LIKE(pesel, '^[0-9]{11}$')),
  CONSTRAINT ck_emp_salary CHECK (monthly_salary > 0),
  CONSTRAINT ck_emp_role   CHECK (employee_role IN ('ADMIN','MANAGER','CLERK'))
);

-- Podklasa USERS: klient
CREATE TABLE customers (
  user_id                NUMBER            PRIMARY KEY,
  drivers_license_no     VARCHAR2(20 CHAR) NOT NULL,
  license_issue_date     DATE              NOT NULL,
  CONSTRAINT fk_cust_user FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE,
  CONSTRAINT uq_cust_license UNIQUE (drivers_license_no)
);

-- Konkretny egzemplarz pojazdu we flocie
CREATE TABLE vehicles (
  vehicle_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
  branch_id        NUMBER            NOT NULL,
  vehicle_type_id  NUMBER            NOT NULL,
  license_plate    VARCHAR2(10 CHAR) NOT NULL,
  vin              CHAR(17)          NOT NULL,
  color            VARCHAR2(30 CHAR),
  mileage          NUMBER(8)         DEFAULT 0 NOT NULL,
  vehicle_status   VARCHAR2(12 CHAR) DEFAULT 'AVAILABLE' NOT NULL,
  CONSTRAINT fk_veh_branch FOREIGN KEY (branch_id)       REFERENCES branches(branch_id),
  CONSTRAINT fk_veh_type   FOREIGN KEY (vehicle_type_id) REFERENCES vehicle_types(vehicle_type_id),
  CONSTRAINT uq_veh_plate  UNIQUE (license_plate),
  CONSTRAINT uq_veh_vin    UNIQUE (vin),
  CONSTRAINT ck_veh_mileage CHECK (mileage >= 0),
  CONSTRAINT ck_veh_status CHECK (vehicle_status IN ('AVAILABLE','RENTED','MAINTENANCE','RETIRED'))
);


/* =====================================================================
   3. TABELE TRANSAKCYJNE
   ===================================================================== */

-- Rezerwacja / wypożyczenie (cały cykl: RESERVED -> ACTIVE -> COMPLETED | CANCELLED)
CREATE TABLE bookings (
  booking_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
  customer_id         NUMBER NOT NULL,
  vehicle_id          NUMBER NOT NULL,
  employee_id         NUMBER NOT NULL,          -- pracownik obsługujący
  promotion_id        NUMBER,
  booking_status      VARCHAR2(10 CHAR) DEFAULT 'RESERVED' NOT NULL,
  start_date          DATE NOT NULL,
  planned_end_date    DATE NOT NULL,
  actual_return_date  DATE,
  start_mileage       NUMBER(8),
  end_mileage         NUMBER(8),
  total_cost          NUMBER(10,2),             -- kwota rozliczona przy zwrocie (fakt historyczny – stawki mogą się zmienić)
  created_at          DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT fk_book_customer  FOREIGN KEY (customer_id)  REFERENCES customers(user_id),
  CONSTRAINT fk_book_vehicle   FOREIGN KEY (vehicle_id)   REFERENCES vehicles(vehicle_id),
  CONSTRAINT fk_book_employee  FOREIGN KEY (employee_id)  REFERENCES employees(user_id),
  CONSTRAINT fk_book_promotion FOREIGN KEY (promotion_id) REFERENCES promotions(promotion_id),
  CONSTRAINT ck_book_status CHECK (booking_status IN ('RESERVED','ACTIVE','COMPLETED','CANCELLED')),
  CONSTRAINT ck_book_dates  CHECK (planned_end_date > start_date),
  CONSTRAINT ck_book_return CHECK (actual_return_date IS NULL OR actual_return_date >= start_date),
  CONSTRAINT ck_book_mileage CHECK (end_mileage IS NULL OR end_mileage >= start_mileage),
  CONSTRAINT ck_book_cost   CHECK (total_cost IS NULL OR total_cost >= 0),
  CONSTRAINT ck_book_completed CHECK (
        booking_status <> 'COMPLETED'
     OR (actual_return_date IS NOT NULL AND end_mileage IS NOT NULL AND total_cost IS NOT NULL))
);

-- Zapisane karty klienta (bez CVV i pełnego numeru – tego nie wolno przechowywać)
CREATE TABLE payment_details (
  payment_details_id  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
  customer_id         NUMBER            NOT NULL,
  card_type           VARCHAR2(12 CHAR) NOT NULL,
  card_last4          CHAR(4)           NOT NULL,
  card_holder_name    VARCHAR2(100 CHAR) NOT NULL,
  expiry_date         DATE              NOT NULL,
  CONSTRAINT fk_pd_customer FOREIGN KEY (customer_id) REFERENCES customers(user_id) ON DELETE CASCADE,
  CONSTRAINT ck_pd_type  CHECK (card_type IN ('VISA','MASTERCARD','AMEX','MAESTRO')),
  CONSTRAINT ck_pd_last4 CHECK (REGEXP_LIKE(card_last4, '^[0-9]{4}$'))
);

-- Wpłaty / zwroty powiązane z rezerwacją
CREATE TABLE transactions (
  transaction_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
  booking_id          NUMBER            NOT NULL,
  payment_details_id  NUMBER,                    -- wymagane tylko dla płatności kartą
  amount              NUMBER(10,2)      NOT NULL,
  transaction_date    DATE DEFAULT SYSDATE NOT NULL,
  payment_method      VARCHAR2(10 CHAR) NOT NULL,
  transaction_type    VARCHAR2(12 CHAR) DEFAULT 'PAYMENT' NOT NULL,
  CONSTRAINT fk_tr_booking FOREIGN KEY (booking_id)         REFERENCES bookings(booking_id),
  CONSTRAINT fk_tr_pd      FOREIGN KEY (payment_details_id) REFERENCES payment_details(payment_details_id),
  CONSTRAINT ck_tr_amount  CHECK (amount > 0),
  CONSTRAINT ck_tr_method  CHECK (payment_method IN ('CARD','CASH','TRANSFER')),
  CONSTRAINT ck_tr_type    CHECK (transaction_type IN ('DEPOSIT','PAYMENT','DAMAGE_FEE','REFUND')),
  CONSTRAINT ck_tr_card    CHECK (payment_method <> 'CARD' OR payment_details_id IS NOT NULL)
);

-- Szkody zgłoszone przy zwrocie pojazdu
CREATE TABLE damages (
  damage_id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
  booking_id           NUMBER             NOT NULL,
  description          VARCHAR2(400 CHAR) NOT NULL,
  severity             VARCHAR2(6 CHAR)   DEFAULT 'LOW' NOT NULL,
  repair_cost          NUMBER(10,2),
  charged_to_customer  CHAR(1)            DEFAULT 'N' NOT NULL,
  reported_date        DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT fk_dmg_booking FOREIGN KEY (booking_id) REFERENCES bookings(booking_id),
  CONSTRAINT ck_dmg_severity CHECK (severity IN ('LOW','MEDIUM','HIGH')),
  CONSTRAINT ck_dmg_cost    CHECK (repair_cost IS NULL OR repair_cost >= 0),
  CONSTRAINT ck_dmg_charged CHECK (charged_to_customer IN ('Y','N'))
);

-- Historia serwisu / przeglądów
CREATE TABLE maintenance (
  maintenance_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
  vehicle_id           NUMBER NOT NULL,
  maintenance_type_id  NUMBER NOT NULL,
  employee_id          NUMBER,                   -- kto zlecił
  start_date           DATE   NOT NULL,
  end_date             DATE,                     -- NULL = serwis w toku
  mileage_at_service   NUMBER(8) NOT NULL,
  cost                 NUMBER(10,2),
  description          VARCHAR2(400 CHAR),
  CONSTRAINT fk_mnt_vehicle  FOREIGN KEY (vehicle_id)          REFERENCES vehicles(vehicle_id),
  CONSTRAINT fk_mnt_type     FOREIGN KEY (maintenance_type_id) REFERENCES maintenance_types(maintenance_type_id),
  CONSTRAINT fk_mnt_employee FOREIGN KEY (employee_id)         REFERENCES employees(user_id),
  CONSTRAINT ck_mnt_dates CHECK (end_date IS NULL OR end_date >= start_date),
  CONSTRAINT ck_mnt_cost  CHECK (cost IS NULL OR cost >= 0)
);


/* =====================================================================
   4. INDEKSY NA KLUCZACH OBCYCH
   ===================================================================== */
CREATE INDEX ix_vtype_make      ON vehicle_types(make_id);
CREATE INDEX ix_emp_branch      ON employees(branch_id);
CREATE INDEX ix_veh_branch      ON vehicles(branch_id);
CREATE INDEX ix_veh_type        ON vehicles(vehicle_type_id);
CREATE INDEX ix_book_customer   ON bookings(customer_id);
CREATE INDEX ix_book_vehicle    ON bookings(vehicle_id, start_date, planned_end_date);
CREATE INDEX ix_book_employee   ON bookings(employee_id);
CREATE INDEX ix_book_promotion  ON bookings(promotion_id);
CREATE INDEX ix_pd_customer     ON payment_details(customer_id);
CREATE INDEX ix_tr_booking      ON transactions(booking_id);
CREATE INDEX ix_tr_pd           ON transactions(payment_details_id);
CREATE INDEX ix_dmg_booking     ON damages(booking_id);
CREATE INDEX ix_mnt_vehicle     ON maintenance(vehicle_id);
CREATE INDEX ix_mnt_type        ON maintenance(maintenance_type_id);
CREATE INDEX ix_mnt_employee    ON maintenance(employee_id);


